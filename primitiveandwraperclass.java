package Yashugowa;
public class primitiveandwraperclass {
	    public static void main(String[] args) {

	        // Primitive data types
	        byte a = 10;
	        short b = 20;
	        int c = 30;
	        long d = 40L;
	        float e = 50.5f;
	        double f = 60.5;
	        char g = 'A';
	        boolean h = true;
	        
	     //Wrapper class
	        Byte w1 = a;
	        Short w2 = b;
	        Integer w3 = c;
	        Long w4 = d;
	        Float w5 = e;
	        Double w6 = f;
	        Character w7 = g;
	        Boolean w8 = h;

	        System.out.println("byte     : " + w1);
	        System.out.println("short    : " + w2);
	        System.out.println("int      : " + w3);
	        System.out.println("long     : " + w4);
	        System.out.println("float    : " + w5);
	        System.out.println("double   : " + w6);
	        System.out.println("char     : " + w7);
	        System.out.println("boolean  : " + w8);
	    }
	}